SELECT
	R.ROUTE_NO,
	R.DEPARTURE_AIRPORT,
	R.ARRIVAL_AIRPORT,
	A.AIRPORT_NAME ->> 'ru' AS DEPARTURE_AIRPORT_NAME,
	F.ACTUAL_ARRIVAL
FROM
	FLIGHTS AS F
	JOIN ROUTES AS R ON R.ROUTE_NO = F.ROUTE_NO
	JOIN AIRPORTS_DATA AS A ON A.AIRPORT_CODE = R.DEPARTURE_AIRPORT
WHERE
	STATUS = 'Arrived'
ORDER BY
	F.ACTUAL_ARRIVAL DESC
LIMIT
	20;